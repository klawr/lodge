//! Shell-level setup: git's `safe.directory`, the container's `PATH` for login
//! shells, and aliases.

use anyhow::Result;
use std::collections::BTreeMap;

use crate::layout;
use crate::output::{info, plural, warning};
use crate::runtime::{Env, ExecOpts, User};
use crate::shell::shell_quote;

// Registers git `safe.directory` entries for the session user (`--global` is
// that user's ~/.gitconfig). Injected plugin repos and the mounted workspace are
// owned by the host uid, which often isn't the session user's, so without this
// git aborts with "detected dubious ownership" and anything that shells out to
// git (lazy.nvim, gitsigns, …) fails. Idempotent: only adds an entry that isn't
// already present. No-op if the container has no git.
pub(super) fn configure_git_safe(env: &dyn Env, dirs: &[String], user: User) -> Result<()> {
    if dirs.is_empty() {
        return Ok(());
    }
    if !env.has_command("git") {
        warning!("git not found in container; skipping safe.directory setup");
        return Ok(());
    }

    info!(
        "marking {}",
        plural(dirs.len(), "git safe.directory", "git safe.directories")
    );
    for dir in dirs {
        let q = crate::shell::shell_quote(dir);
        let script = format!(
            "git config --global --get-all safe.directory 2>/dev/null | grep -qxF {q} \
             || git config --global --add safe.directory {q}"
        );
        env.exec(
            &["sh", "-c", &script],
            &ExecOpts {
                user,
                ..ExecOpts::default()
            },
        )?;
    }
    Ok(())
}

// Login shells source /etc/profile, which on many distros resets PATH to a
// minimal system default — dropping anything added via Docker ENV. Read the
// container's current PATH and write it into /etc/profile.d/ so it survives.
pub(super) fn preserve_path(env: &dyn Env) -> Result<()> {
    let path = match env.exec_capture(&["printenv", "PATH"]) {
        Ok(p) => p.trim().to_string(),
        Err(_) => return Ok(()),
    };
    if path.is_empty() {
        return Ok(());
    }
    let script = format!("export PATH={}\n", crate::shell::shell_quote(&path));
    env.write_file(layout::PROFILE_PATH, script.as_bytes())
}

pub(super) fn inject_aliases(env: &dyn Env, aliases: &BTreeMap<String, String>) -> Result<()> {
    if aliases.is_empty() {
        return Ok(());
    }

    let mut content = String::from("# Generated by lodge — do not edit\n");
    // A BTreeMap iterates in name order, so the file is deterministic.
    for (name, cmd) in aliases {
        content.push_str(&format!("alias {}={}\n", name, shell_quote(cmd)));
    }

    env.write_file(layout::PROFILE_ALIASES, content.as_bytes())?;
    info!("installed {}", plural(aliases.len(), "alias", "aliases"));

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::runtime::fake::FakeEnv;

    #[test]
    fn aliases_are_written_sorted_and_quoted() {
        let env = FakeEnv::new();
        let aliases = BTreeMap::from([
            ("ll".to_string(), "ls -la".to_string()),
            ("ga".to_string(), "git add 'x'".to_string()),
        ]);
        inject_aliases(&env, &aliases).unwrap();
        assert_eq!(
            env.file("/etc/profile.d/lodge.sh").unwrap(),
            "# Generated by lodge — do not edit\nalias ga='git add '\\''x'\\'''\nalias ll='ls -la'\n"
        );
    }

    #[test]
    fn no_aliases_writes_nothing() {
        let env = FakeEnv::new();
        inject_aliases(&env, &BTreeMap::new()).unwrap();
        assert!(env.file("/etc/profile.d/lodge.sh").is_none());
    }

    #[test]
    fn container_path_survives_login_shells() {
        let env = FakeEnv::new().with_var("PATH", "/opt/tool/bin:/usr/bin");
        preserve_path(&env).unwrap();
        assert_eq!(
            env.file("/etc/profile.d/lodge-path.sh").unwrap(),
            "export PATH='/opt/tool/bin:/usr/bin'\n"
        );
    }

    #[test]
    fn safe_directories_are_set_for_the_session_user() {
        let env = FakeEnv::new().with_commands(&["git"]);
        configure_git_safe(&env, &["*".to_string()], User::Named("dev")).unwrap();
        let script = "git config --global --get-all safe.directory 2>/dev/null | grep -qxF '*' \
                      || git config --global --add safe.directory '*'";
        assert_eq!(
            env.ran_as(&["sh", "-c", script]),
            Some(crate::runtime::fake::Who::Named("dev".into()))
        );
    }

    #[test]
    fn missing_path_is_not_an_error() {
        let env = FakeEnv::new(); // no PATH variable
        preserve_path(&env).unwrap();
        assert!(env.file("/etc/profile.d/lodge-path.sh").is_none());
    }
}
