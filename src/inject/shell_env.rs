//! Shell-level setup: git's `safe.directory`, the container's `PATH` for login
//! shells, aliases, and the user's terminal.

use anyhow::Result;
use std::collections::HashMap;

use crate::output::{info, warning};
use crate::runtime::{Env, ExecOpts};
use crate::shell::shell_quote;
// Registers git `safe.directory` entries inside the container. Injected plugin
// repos and the mounted workspace are owned by the host uid, but git runs as
// root in the container, so without this git aborts with "detected dubious
// ownership" and anything that shells out to git (lazy.nvim, gitsigns, …) fails.
// Idempotent: only adds an entry that isn't already present. No-op if the
// container has no git.
pub(super) fn configure_git_safe(env: &dyn Env, dirs: &[String]) -> Result<()> {
    if dirs.is_empty() {
        return Ok(());
    }
    if !env.has_command("git") {
        warning!("git not found in container; skipping safe.directory setup");
        return Ok(());
    }

    info!(
        "marking {} git safe.director{}",
        dirs.len(),
        if dirs.len() == 1 { "y" } else { "ies" }
    );
    for dir in dirs {
        let q = crate::shell::shell_quote(dir);
        let script = format!(
            "git config --global --get-all safe.directory 2>/dev/null | grep -qxF {q} \
             || git config --global --add safe.directory {q}"
        );
        env.exec(&["sh", "-c", &script], &ExecOpts::default())?;
    }
    Ok(())
}

// Login shells source /etc/profile, which on many distros resets PATH to a
// minimal system default — dropping anything added via Docker ENV. Read the
// container's current PATH and write it into /etc/profile.d/ so it survives.
pub(super) fn inject_docker_path(env: &dyn Env) -> Result<()> {
    let path = match env.exec_capture(&["printenv", "PATH"]) {
        Ok(p) => p.trim().to_string(),
        Err(_) => return Ok(()),
    };
    if path.is_empty() {
        return Ok(());
    }
    let script = format!("export PATH={}\n", crate::shell::shell_quote(&path));
    env.write_file("/etc/profile.d/lodge-path.sh", script.as_bytes())
}

pub(super) fn inject_aliases(env: &dyn Env, aliases: &HashMap<String, String>) -> Result<()> {
    if aliases.is_empty() {
        return Ok(());
    }

    let mut content = String::from("# Generated by lodge — do not edit\n");
    let mut pairs: Vec<_> = aliases.iter().collect();
    pairs.sort_by_key(|(k, _)| k.as_str());
    for (name, cmd) in pairs {
        content.push_str(&format!("alias {}={}\n", name, shell_quote(cmd)));
    }

    env.write_file("/etc/profile.d/lodge.sh", content.as_bytes())?;
    info!(
        "installed {} alias{}",
        aliases.len(),
        if aliases.len() == 1 { "" } else { "es" }
    );

    Ok(())
}

// Makes the user's terminal known inside the container. Best effort: a missing
// terminfo entry only costs some colours, so it never fails the injection.
pub(super) fn inject_terminfo(env: &dyn Env) {
    if let Some(term) = crate::terminfo::local_term()
        && let Err(e) = crate::terminfo::ensure(env, &term)
    {
        warning!("could not copy the terminfo entry for {term}: {e:#}");
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::runtime::fake::FakeEnv;

    #[test]
    fn aliases_are_written_sorted_and_quoted() {
        let env = FakeEnv::new();
        let aliases = HashMap::from([
            ("ll".to_string(), "ls -la".to_string()),
            ("ga".to_string(), "git add 'x'".to_string()),
        ]);
        inject_aliases(&env, &aliases).unwrap();
        assert_eq!(
            env.file("/etc/profile.d/lodge.sh").unwrap(),
            "# Generated by lodge — do not edit\nalias ga='git add '\\''x'\\'''\nalias ll='ls -la'\n"
        );
    }

    #[test]
    fn no_aliases_writes_nothing() {
        let env = FakeEnv::new();
        inject_aliases(&env, &HashMap::new()).unwrap();
        assert!(env.file("/etc/profile.d/lodge.sh").is_none());
    }

    #[test]
    fn container_path_survives_login_shells() {
        let env = FakeEnv::new().with_var("PATH", "/opt/tool/bin:/usr/bin");
        inject_docker_path(&env).unwrap();
        assert_eq!(
            env.file("/etc/profile.d/lodge-path.sh").unwrap(),
            "export PATH='/opt/tool/bin:/usr/bin'\n"
        );
    }

    #[test]
    fn missing_path_is_not_an_error() {
        let env = FakeEnv::new(); // no PATH variable
        inject_docker_path(&env).unwrap();
        assert!(env.file("/etc/profile.d/lodge-path.sh").is_none());
    }
}
